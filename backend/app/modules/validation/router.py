"""API for validation plans (ENG-039): generate, read, approve, and the AC-to-test matrix.

Plans are generated by the ``planning.plan_validation`` capability (bound to the
project, so its H-MEM lessons can shape the tests) and stored through M2's
repository on the request session. Errors answer 404 (unknown project, set,
contract or plan), 409 (unlocked set, no criteria, stale or non-draft plan)
and 422 (invalid input).
"""

import uuid

from fastapi import APIRouter, Depends, FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from app.core.db import get_session
from app.domain.enums import ValidationLevel
from app.domain.ports import LLMPort
from app.domain.validation_plan import ValidationPlan
from app.modules.capabilities.api import validation_capability
from app.modules.persistence.errors import ProjectNotFoundError
from app.modules.persistence.repository import get_project
from app.modules.persistence.requirements_repository import SqlAlchemyArtifactRepository
from app.modules.validation.errors import ValidationPlanError
from app.modules.validation.plan import DEFAULT_REQUIRED_LEVELS, ValidationPlanService
from app.modules.validation.traceability import TraceabilityMatrix

router = APIRouter(prefix="/projects/{project_id}/validation-plans", tags=["validation"])

_ID = r"^[A-Z]{2,5}-\d{3,}$"


class ValidationPlanRequest(BaseModel):
    requirements_set_id: str = Field(pattern=_ID)
    contract_ids: list[str] = Field(default_factory=list, max_length=20)
    required_levels: list[ValidationLevel] = Field(default_factory=lambda: list(DEFAULT_REQUIRED_LEVELS), min_length=1)
    context: str = Field(default="", max_length=4000)


def get_service(
    project_id: uuid.UUID,
    llm: LLMPort = Depends(validation_capability),
    session: Session = Depends(get_session),
) -> ValidationPlanService:
    """The model dependency resolves first, so an unconfigured runtime fails before any database work."""
    try:
        get_project(session, project_id)
    except ProjectNotFoundError as exc:
        raise HTTPException(status_code=404, detail="project not found") from exc
    return ValidationPlanService(llm=llm, repo=SqlAlchemyArtifactRepository(session))


@router.post("", response_model=ValidationPlan, status_code=201)
async def generate_validation_plan(
    project_id: uuid.UUID, payload: ValidationPlanRequest, svc: ValidationPlanService = Depends(get_service)
) -> ValidationPlan:
    """Test intents for every criterion of a locked requirements set, as a draft plan."""
    return await svc.generate(
        project_id,
        payload.requirements_set_id,
        contract_ids=payload.contract_ids,
        required_levels=payload.required_levels,
        context=payload.context,
    )


@router.get("/{plan_id}", response_model=ValidationPlan)
async def get_validation_plan(
    project_id: uuid.UUID, plan_id: str, svc: ValidationPlanService = Depends(get_service)
) -> ValidationPlan:
    return await svc.get(project_id, plan_id)


@router.post("/{plan_id}/approve", response_model=ValidationPlan)
async def approve_validation_plan(
    project_id: uuid.UUID, plan_id: str, svc: ValidationPlanService = Depends(get_service)
) -> ValidationPlan:
    """Draft -> accepted (a new version); refused when its pinned inputs changed."""
    return await svc.approve(project_id, plan_id)


@router.get("/{plan_id}/matrix", response_model=TraceabilityMatrix)
async def validation_matrix(
    project_id: uuid.UUID, plan_id: str, svc: ValidationPlanService = Depends(get_service)
) -> TraceabilityMatrix:
    """AC-to-test matrix: tests and checks per criterion and level, gaps and staleness."""
    return await svc.matrix(project_id, plan_id)


def install_validation_error_handlers(app: FastAPI) -> None:
    @app.exception_handler(ValidationPlanError)
    async def _validation_error(request: Request, exc: ValidationPlanError) -> JSONResponse:
        return JSONResponse(status_code=exc.status_code, content={"error": {"kind": exc.kind, "message": str(exc)}})
